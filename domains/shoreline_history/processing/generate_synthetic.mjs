/**
 * Synthetic Shoreline-History Generator
 * ======================================
 * Generates simulated shoreline-position observations for pipeline testing.
 * OUTPUT IS SYNTHETIC — not field measurements or satellite-derived observations.
 *
 * Model: parameterised random-walk along the cross-shore axis anchored at
 * the Cuddalore study site. Three scenario types are included:
 *   1. erosion    — net landward retreat
 *   2. accretion  — net seaward advance
 *   3. stable     — near-zero net displacement
 *
 * Usage:
 *   node domains/shoreline_history/processing/generate_synthetic.mjs [seed]
 */

import { writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dir = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(__dir, '..', 'data', 'synthetic');

// ── Seeded pseudo-random (Mulberry32) ────────────────────────────────────────
function mulberry32(seed) {
  return () => {
    seed |= 0; seed = seed + 0x6D2B79F5 | 0;
    let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}

const SEED = parseInt(process.argv[2] ?? '42', 10);
const rand = mulberry32(SEED);

// ── Study-area anchor points (WGS-84) ────────────────────────────────────────
const ANCHOR_POINTS = [
  { id: 'P1', lat: 11.760, lon: 79.7750 },
  { id: 'P2', lat: 11.750, lon: 79.7730 },
  { id: 'P3', lat: 11.740, lon: 79.7710 },
  { id: 'P4', lat: 11.730, lon: 79.7690 },
];

// ── Date series: roughly every 3 years from 1990 to 2024 ─────────────────────
const YEARS = [1990, 1993, 1996, 1999, 2002, 2005, 2008, 2011, 2014, 2017, 2020, 2023, 2024];

// ── Scenario generator ───────────────────────────────────────────────────────
function generateScenario(name, trendMperYear, noiseSigmaM) {
  const observations = [];
  for (const pt of ANCHOR_POINTS) {
    let displacement = 0;
    const ptRand = mulberry32(SEED ^ pt.id.charCodeAt(1));
    for (let i = 0; i < YEARS.length; i++) {
      const dt = i === 0 ? 0 : YEARS[i] - YEARS[i - 1];
      const noise = (ptRand() - 0.5) * 2 * noiseSigmaM;
      displacement += trendMperYear * dt + noise;
      observations.push({
        scenario: name,
        transect_id: pt.id,
        date: `${YEARS[i]}-06-15`,
        lat: pt.lat,
        lon: pt.lon,
        displacement_m: parseFloat(displacement.toFixed(2)),
        annual_rate_m_yr: i === 0 ? null : parseFloat((trendMperYear + noise / dt).toFixed(3)),
        data_origin: 'SYNTHETIC',
        synthetic: true,
        notes: 'Simulated random-walk — not a measured shoreline position'
      });
    }
  }
  return observations;
}

const erosion    = generateScenario('erosion',    -1.2, 3.5);
const accretion  = generateScenario('accretion',  +0.8, 2.5);
const stable     = generateScenario('stable',      0.0, 1.8);

const all = [...erosion, ...accretion, ...stable];

// ── Write outputs ─────────────────────────────────────────────────────────────
mkdirSync(OUT_DIR, { recursive: true });

writeFileSync(
  join(OUT_DIR, 'shoreline_observations.json'),
  JSON.stringify({
    metadata: {
      data_origin: 'SYNTHETIC',
      synthetic: true,
      generator_version: '1.0.0',
      generation_timestamp: new Date().toISOString(),
      seed: SEED,
      domain: 'shoreline_history',
      study_area: 'Cuddalore Coast, Tamil Nadu, India',
      crs: 'WGS-84 (EPSG:4326)',
      units: { displacement_m: 'metres (cross-shore)', annual_rate_m_yr: 'metres/year' },
      scenarios: ['erosion', 'accretion', 'stable'],
      limitations: [
        'These are simulated observations generated by a random-walk model.',
        'They are NOT derived from satellite imagery or field surveys.',
        'Do not use as evidence of actual shoreline change.',
      ],
    },
    records: all,
  }, null, 2)
);

// Summary table CSV
const csvLines = ['scenario,transect_id,date,lat,lon,displacement_m,annual_rate_m_yr,synthetic'];
for (const r of all) {
  csvLines.push(`${r.scenario},${r.transect_id},${r.date},${r.lat},${r.lon},${r.displacement_m},${r.annual_rate_m_yr ?? ''},true`);
}
writeFileSync(join(OUT_DIR, 'shoreline_observations.csv'), csvLines.join('\n'));

console.log(`[shoreline_history] Synthetic data written to ${OUT_DIR}`);
console.log(`  Records: ${all.length}  |  Seed: ${SEED}`);
